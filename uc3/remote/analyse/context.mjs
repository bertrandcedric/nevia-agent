// CONTEXT.md, what Claude would otherwise work out at the start of each run: the collections and
// their documents, the tables of each one, the infer warnings (without their sample values) and
// how to work on the project.
//   node context.mjs <project dir> <counts.json> <CONTEXT.md> <config> <schema>
// counts.json: {"<collection>": <documents>} for every collection of the database.
import fs from 'node:fs';
import path from 'node:path';
import YAML from 'yaml';

const [project, countsFile, out, config, schema] = process.argv.slice(2);
if (!schema) { console.error('usage: node context.mjs <project dir> <counts.json> <CONTEXT.md> <config> <schema>'); process.exit(2); }
const ROOT = path.join(project, 'source/collections');
const counts = JSON.parse(fs.readFileSync(countsFile, 'utf8'));
const read = (f) => YAML.parse(fs.readFileSync(f, 'utf8'));

const collections = fs.readdirSync(ROOT).filter((c) => fs.statSync(path.join(ROOT, c)).isDirectory()).sort();
const L = ['# Context of the migration', '',
  `Generated by \`analyse\` (${new Date().toISOString().slice(0, 16)}Z): read it instead of exploring.`,
  'The project is `' + project + '`; each run starts from it as it is here.', ''];

L.push('## Collections', '', '| Collection | Documents | Tables | Root table |', '| --- | ---: | ---: | --- |');
const tables = {};
for (const c of collections) {
  const maps = fs.readdirSync(path.join(ROOT, c)).filter((f) => /^mapping_.*\.yaml$/.test(f)).sort()
    .map((f) => ({ f, y: read(path.join(ROOT, c, f)) }));
  tables[c] = maps;
  const root = maps.find((m) => m.y.traversal?.mode === 'root');
  L.push(`| ${c} | ${counts[c] ?? '?'} | ${maps.length} | ${root?.y.pg_mapping.table_name ?? '-'} |`);
}
const excluded = Object.keys(counts).filter((c) => !collections.includes(c)).sort();
L.push('', `Not in the project (excluded in ${config}, all empty): ${excluded.length} collections: ${excluded.join(', ')}.`, '');

L.push('## Tables', '', 'Per collection: table ← parent (foreign key), MongoDB path, columns (target name: SQL type, `?` nullable).', '');
for (const c of collections) {
  L.push(`### ${c}`, '');
  for (const { f, y } of tables[c]) {
    const m = y.pg_mapping;
    const parent = y.traversal?.mode === 'root' ? 'root' : `← ${y.traversal.parent_table} (${y.traversal.fk_column})`;
    const cols = m.ddl.columns.map((x) => `${x.name}: ${x.sql_type}${x.nullable ? '?' : ''}`).join(', ');
    L.push(`- \`${m.table_name}\` ${parent}, \`${y.mongo_path}\`, ${y.traversal?.mode ?? '?'} (${f}): ${cols}`);
  }
  L.push('');
}

L.push('## Infer warnings', '', 'From source/collections/<collection>/<collection>.stats.yaml, sample values left out.', '',
  '| Collection | Kind | Field | Details |', '| --- | --- | --- | --- |');
for (const c of collections) {
  const f = path.join(ROOT, c, `${c}.stats.yaml`);
  for (const w of (fs.existsSync(f) ? read(f)?.infer_warnings : null) ?? []) {
    const d = [];
    if (w.dominant_family) d.push(`${w.dominant_family} ${Math.round((w.dominant_ratio ?? 0) * 100)} %`);
    for (const x of w.minority_families ?? []) d.push(`${x.family} ${Math.round(x.ratio * 100)} %`);
    if (w.keyword) d.push(`keyword ${w.keyword}${w.renamed_to ? `, renamed to ${w.renamed_to}` : ''}`);
    for (const [k, v] of Object.entries(w)) {
      if (!['kind', 'field_path', 'dominant_family', 'dominant_ratio', 'minority_families', 'observed_types', 'keyword', 'renamed_to'].includes(k)) {
        d.push(`${k}: ${typeof v === 'object' ? JSON.stringify(v) : v}`);
      }
    }
    L.push(`| ${c} | ${w.kind} | ${w.field_path ?? ''} | ${d.join('; ').replace(/\|/g, '\\|')} |`);
  }
}
L.push('');

L.push('## Working on the project', '',
  '- The mappings are the source: edit `pg_mapping.columns` (what export writes) and `pg_mapping.ddl` (the table) together,',
  `  then \`mongo2pg to-pg -c <config> --schema ${schema} [<collection>]\` regenerates schema/tables/, and`,
  '  `mongo2pg export -c <config> [<collection>]` the CSV in data/ (export reads the generated SQL).',
  '- Do not run `mongo2pg infer` again: it regenerates the mappings and your changes are lost.',
  '- A branch: `mongo2pg import -c <branch config> --log-level error` creates the tables and loads the CSV, once per branch, run right after `nvpg branch` (which prints this command with the path of the config). The main database: `nvpg import main` only.',
  '- The pristine project (as above) is restored at the start of each run: no need to copy it.',
  '- The mongo2pg documentation of this release: `docs/` next to this file (CLI reference, how-tos, usage).', '');
fs.writeFileSync(out, `${L.join('\n')}\n`);
console.log(`[context] ${out}: ${collections.length} collections, ${Object.values(tables).flat().length} tables`);
